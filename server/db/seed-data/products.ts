  black: { valueAr: 'أسود', valueEn: 'Black', hex: '#1A1A1D' },
  blue: { valueAr: 'أزرق', valueEn: 'Blue', hex: '#1E3A8A' },
  green: { valueAr: 'أخضر', valueEn: 'Green', hex: '#14532D' },
  silver: { valueAr: 'فضي', valueEn: 'Silver', hex: '#C7C9CC' },
  gold: { valueAr: 'ذهبي', valueEn: 'Gold', hex: '#B8860B' },
  white: { valueAr: 'أبيض', valueEn: 'White', hex: '#F2F2F3' },
  purple: { valueAr: 'بنفسجي', valueEn: 'Purple', hex: '#5B21B6' },
