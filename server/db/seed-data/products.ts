type ColourKey = keyof typeof COLOURS;

const colourOption = (...keys: ColourKey[]) => ({
  nameAr: 'اللون',
  nameEn: 'Colour',
  isColor: true,
  values: keys.map((key) => ({ ...COLOURS[key] })),
});

